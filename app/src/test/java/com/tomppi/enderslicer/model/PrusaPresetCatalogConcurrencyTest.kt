package com.tomppi.enderslicer.model

import java.io.File
import java.util.Collections
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test

/**
 * The preset resolution caches under the concurrency they are actually filled at: the walks run
 * on Dispatchers.IO, one per printer selection, and quick selections overlap with each other and
 * with the initial catalogue load. Whatever the interleaving, every walk resolves exactly what
 * the sequential one does - the caches are filled under one lock, where a plain HashMap's
 * getOrPut used to tear and leave a picker empty or wrong for the session.
 *
 * Skips itself when the repository JSON is absent (it is generated by the fetch script), like
 * [PrusaPresetCatalogSnapshotTest].
 */
class PrusaPresetCatalogConcurrencyTest {

    private val presetJson = File("src/main/assets/prusa-presets.json")

    /** Everything the pickers and the slice read for a few machines, in a comparable shape. */
    private fun resolveAll(catalog: PrusaPresetCatalog, printerIds: List<String>): List<Any?> {
        val out = mutableListOf<Any?>()
        for (id in printerIds) {
            val printer = catalog.printer(id)!!
            val print = catalog.defaultPrint(printer)
            val filament = catalog.defaultFilament(printer)
            out.add(catalog.printerOptions())
            out.add(catalog.printOptions(printer))
            out.add(catalog.filamentOptions(printer))
            out.add(catalog.resolvePrinter(printer))
            out.add(print)
            out.add(print?.let { catalog.resolvePrint(printer, it) })
            out.add(filament?.let { catalog.resolveFilament(printer, it) })
        }
        return out
    }

    @Test
    fun concurrentWalksResolveTheSameValuesAsSequentialOnes() {
        assumeTrue(presetJson.isFile)
        val text = presetJson.readText()
        val ids = listOf("mk4", "xl-2t", "c1")
        val expected = resolveAll(PrusaPresetCatalog(PrusaPresetRepository.parse(text)), ids)

        // One catalogue, as the app has it: the concurrent walks share its caches.
        val shared = PrusaPresetCatalog(PrusaPresetRepository.parse(text))
        val results = Collections.synchronizedList(mutableListOf<List<Any?>>())
        val failures = Collections.synchronizedList(mutableListOf<Throwable>())
        val threads = (1..6).map {
            Thread {
                try {
                    repeat(3) { results += resolveAll(shared, ids) }
                } catch (error: Throwable) {
                    failures += error
                }
            }
        }
        threads.forEach(Thread::start)
        threads.forEach(Thread::join)

        assertTrue(
            "no walk may fail or tear a cache: " + failures.joinToString(),
            failures.isEmpty(),
        )
        assertEquals("every walk ran to the end", 18, results.size)
        results.forEach { assertEquals("and resolved the sequential walk's values", expected, it) }
    }
}
