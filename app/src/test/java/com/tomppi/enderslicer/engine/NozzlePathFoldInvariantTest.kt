package com.tomppi.enderslicer.engine

import java.io.File
import java.util.Locale
import kotlin.math.hypot
import kotlin.math.max
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test

/**
 * What a preview budget may fold, and what it may not - in either parser.
 *
 * Past its budget each parser replaces moves with longer ones, because a ribbon move costs
 * roughly 800 bytes and the phone has to hold the path. The one straight move drawn for a fold
 * may only stand for moves that genuinely continue it - the same kind of move, in the same
 * direction. A fold closed at a move that turns draws a chord across the corner, a fold closed
 * at a move that extrudes after a travel paints a bead where the printer only travelled, and a
 * move the budget simply throws away is a gap in a wall. The Cura parser drew 513 beads over
 * more than 5 mm of travel on the reported print; the Prusa one skipped 1.4 million of the 2.4
 * million moves of a 0.08 mm print, which is what made its walls patchy up close.
 *
 * The check is on the source moves: everything a drawn move stands for has to lie on the line
 * that was drawn, and the drawn moves have to cover every source move exactly once, in order.
 */
class NozzlePathFoldInvariantTest {

    /** How far a source move may sit from the straight line drawn for it, in millimetres. */
    private val driftMm = 0.2

    private val voxel = GcodeNozzlePath.VALUES_PER_MOVE
    private val kindOffset = GcodeNozzlePath.KIND
    private val x1 = GcodeNozzlePath.X1
    private val y1 = GcodeNozzlePath.Y1
    private val x2 = GcodeNozzlePath.X2
    private val y2 = GcodeNozzlePath.Y2

    /** The reported prints, when they are on this machine: -DrealGcode / -DrealPrusaGcode. */
    private val realCura = File(System.getProperty("realGcode") ?: System.getenv("REAL_GCODE").orEmpty())
    private val realPrusa = File(System.getProperty("realPrusaGcode") ?: System.getenv("REAL_PRUSA_GCODE").orEmpty())

    /** A Cura serpentine past the budget: straight lines with a travel between them. */
    private fun curaSerpentine(layers: Int = 30, lines: Int = 25, steps: Int = 60): File {
        val file = File.createTempFile("nozzle-path-serpentine", ".gcode").also { it.deleteOnExit() }
        file.bufferedWriter().use { out ->
            out.append(";FLAVOR:Marlin\n;Layer height: 0.2\nM82\nG92 E0\nG28\nG0 X0 Y0 Z0.2\n")
            var e = 0L
            var y = 0
            for (layer in 0 until layers) {
                if (layer > 0) {
                    out.append("G0 Z").append(String.format(Locale.US, "%.2f", layer * 0.2 + 0.2)).append(" F600\n")
                }
                for (line in 0 until lines) {
                    y++
                    val from = if (line % 2 == 0) 0 else steps
                    val to = if (line % 2 == 0) steps else 0
                    out.append("G0 X" + from + " Y" + y + " F6000\n")
                    for (step in 1..steps) {
                        e += 100
                        out.append("G1 X" + (from + (to - from) * step / steps) + " Y" + y)
                        out.append(" E" + String.format(Locale.US, "%.3f", e / 1000.0) + "\n")
                    }
                }
            }
        }
        return file
    }

    /** The same shape in PrusaSlicer's dialect, with its ;LAYER_CHANGE / ;WIDTH: markers. */
    private fun prusaSerpentine(layers: Int = 30, lines: Int = 25, steps: Int = 60): File {
        val file = File.createTempFile("nozzle-path-prusa-serpentine", ".gcode").also { it.deleteOnExit() }
        file.bufferedWriter().use { out ->
            out.append("; generated by PrusaSlicer\n;LAYER_CHANGE\n;Z:0.08\n;HEIGHT:0.08\n;WIDTH:0.42\nM83\nG92 E0\n")
            var e = 0L
            var y = 0
            for (layer in 0 until layers) {
                if (layer > 0) {
                    out.append(";LAYER_CHANGE\n;Z:").append(String.format(Locale.US, "%.2f", layer * 0.08))
                        .append("\n;HEIGHT:0.08\n")
                    out.append("G1 Z").append(String.format(Locale.US, "%.2f", layer * 0.08)).append(" F600\n")
                }
                for (line in 0 until lines) {
                    y++
                    val from = if (line % 2 == 0) 0 else steps
                    val to = if (line % 2 == 0) steps else 0
                    out.append("G1 X" + from + " Y" + y + " F9000\n")
                    for (step in 1..steps) {
                        e += 100
                        out.append("G1 X" + (from + (to - from) * step / steps) + " Y" + y)
                        out.append(" E" + String.format(Locale.US, "%.3f", e / 1000.0) + " F1800\n")
                    }
                }
            }
        }
        return file
    }

    private fun x(moves: FloatArray, index: Int, field: Int) = moves[index * voxel + field].toDouble()

    private fun pointDistance(px: Double, py: Double, ax: Double, ay: Double, bx: Double, by: Double): Double {
        val vx = bx - ax
        val vy = by - ay
        val denominator = vx * vx + vy * vy
        if (denominator <= 1e-12) return hypot(px - ax, py - ay)
        val t = (((px - ax) * vx + (py - ay) * vy) / denominator).coerceIn(0.0, 1.0)
        return hypot(px - (ax + vx * t), py - (ay + vy * t))
    }

    private fun directionDot(moves: FloatArray, a: Int, b: Int): Double {
        val adx = x(moves, a, x2) - x(moves, a, x1)
        val ady = x(moves, a, y2) - x(moves, a, y1)
        val bdx = x(moves, b, x2) - x(moves, b, x1)
        val bdy = x(moves, b, y2) - x(moves, b, y1)
        val al = hypot(adx, ady)
        val bl = hypot(bdx, bdy)
        if (al <= 1e-9 || bl <= 1e-9) return 1.0
        return (adx * bdx + ady * bdy) / (al * bl)
    }

    /**
     * Fails when a drawn move stands for source moves its own line does not cover, and returns
     * the worst distance it saw.
     */
    private fun assertFoldsAreHonest(
        label: String,
        drawnMoves: FloatArray,
        drawnCount: Int,
        drawnSourceIndices: IntArray,
        truncated: Boolean,
        exactMoves: FloatArray,
        exactCount: Int,
    ): Double {
        assertTrue(label + ": the file has to be past the budget", truncated)
        assertTrue(label + ": the budget has to fold something", drawnCount < exactCount)
        var previousSource = -1
        var worstDrift = 0.0
        for (drawn in 0 until drawnCount) {
            val last = drawnSourceIndices[drawn]
            val first = previousSource + 1
            assertTrue(label + ": source moves have to be covered in order", last >= first)
            val ax = x(drawnMoves, drawn, x1)
            val ay = x(drawnMoves, drawn, y1)
            val bx = x(drawnMoves, drawn, x2)
            val by = x(drawnMoves, drawn, y2)
            val kind = drawnMoves[drawn * voxel + kindOffset]
            assertEquals(label + ": span start x", x(exactMoves, first, x1), ax, 1e-3)
            assertEquals(label + ": span start y", x(exactMoves, first, y1), ay, 1e-3)
            assertEquals(label + ": span end x", x(exactMoves, last, x2), bx, 1e-3)
            assertEquals(label + ": span end y", x(exactMoves, last, y2), by, 1e-3)
            for (source in first..last) {
                val sourceKind = exactMoves[source * voxel + kindOffset]
                assertTrue(
                    label + ": a drawn move may not stand for another kind of move (span " + first + ".." + last + ")",
                    sourceKind == kind,
                )
                // The stored moves are floats; the parser compared the doubles it read. A
                // direction exactly on the fold threshold can round either way here.
                assertTrue(
                    label + ": a folded move has to continue the first one (span " + first + ".." + last + ")",
                    directionDot(exactMoves, first, source) >= 0.995 - 1e-4,
                )
                val drift = max(
                    pointDistance(x(exactMoves, source, x1), x(exactMoves, source, y1), ax, ay, bx, by),
                    pointDistance(x(exactMoves, source, x2), x(exactMoves, source, y2), ax, ay, bx, by),
                )
                worstDrift = max(worstDrift, drift)
                assertTrue(
                    label + ": a source move sits " + String.format(Locale.US, "%.3f", drift) +
                        " mm off the line drawn for it (span " + first + ".." + last + ")",
                    drift <= driftMm,
                )
            }
            previousSource = last
        }
        assertEquals(label + ": every source move has to be covered", exactCount, previousSource + 1)
        return worstDrift
    }

    @Test
    fun aTightCuraBudgetFoldsOnlyMovesTheDrawnLineCovers() {
        val file = curaSerpentine()
        val folded = GcodeNozzlePathParser.parse(file, maxMoves = 9_000)
        val exact = GcodeNozzlePathParser.parse(file, maxMoves = Int.MAX_VALUE)
        val worst = assertFoldsAreHonest(
            "cura serpentine",
            folded.moves, folded.moveCount, folded.sourceMoveIndices, folded.truncated,
            exact.moves, exact.moveCount,
        )
        println(
            "cura serpentine: source=" + folded.sourceMoveCount + " drawn=" + folded.moveCount +
                String.format(Locale.US, " worst drift %.4f mm", worst),
        )
    }

    @Test
    fun aTightPrusaBudgetFoldsOnlyMovesTheDrawnLineCovers() {
        val file = prusaSerpentine()
        val folded = PrusaNozzlePathParser.parse(file, maxMoves = 9_000)
        val exact = PrusaNozzlePathParser.parse(file, maxMoves = Int.MAX_VALUE)
        val worst = assertFoldsAreHonest(
            "prusa serpentine",
            folded.moves, folded.moveCount, folded.sourceMoveIndices, folded.truncated,
            exact.moves, exact.moveCount,
        )
        println(
            "prusa serpentine: source=" + folded.sourceMoveCount + " drawn=" + folded.moveCount +
                String.format(Locale.US, " worst drift %.4f mm", worst),
        )
    }

    @Test
    fun theReportedCuraPrintFoldsHonestly() {
        assumeTrue("real cura gcode not available", realCura.isFile)
        val folded = GcodeNozzlePathParser.parse(realCura)
        val exact = GcodeNozzlePathParser.parse(realCura, maxMoves = Int.MAX_VALUE)
        val worst = assertFoldsAreHonest(
            "cura print",
            folded.moves, folded.moveCount, folded.sourceMoveIndices, folded.truncated,
            exact.moves, exact.moveCount,
        )
        println(
            "reported cura print: source=" + folded.sourceMoveCount + " drawn=" + folded.moveCount +
                " extrusions=" + folded.extrusionMoveCount +
                String.format(Locale.US, " worst drift %.4f mm", worst),
        )
    }

    @Test
    fun theReportedPrusaPrintFoldsHonestly() {
        assumeTrue("real prusa gcode not available", realPrusa.isFile)
        val folded = PrusaNozzlePathParser.parse(realPrusa)
        val exact = PrusaNozzlePathParser.parse(realPrusa, maxMoves = Int.MAX_VALUE)
        val worst = assertFoldsAreHonest(
            "prusa print",
            folded.moves, folded.moveCount, folded.sourceMoveIndices, folded.truncated,
            exact.moves, exact.moveCount,
        )
        println(
            "reported prusa print: source=" + folded.sourceMoveCount + " drawn=" + folded.moveCount +
                " extrusions=" + folded.extrusionMoveCount + " layers=" + folded.layerCount +
                String.format(Locale.US, " worst drift %.4f mm", worst),
        )
    }
}
